        <h6 class="fw-bold"><b>Overview</b></h6>
        <p class="text-justify">Clinic / Health Centre (CHCs) are the primary-care tier of Palau?s public system. They are operated by the Division of Primary and Preventive Health Services in the MHHS Bureau of Public Health. MHHS currently lists seven CHCs: Community Health Center I (Koror), Community Health Center II (Airai), Northern Community Health Center (Ngarchelong), Eastern Community Health Center (Melekeok), Southern Community Health Center (Peleliu), Western Community Health Center (Ngeremlengui), and Angaur Community Health Center. The Koror and Airai centers are also called the ?Central? Clinic / Health Centre. All CHCs close for lunch (11:30 AM?12:30 PM) and on weekends and public holidays.</p>
        <p class="text-justify"><strong>Note:</strong> The Code does not define ?Community Health Center? as a facility type and sets no staffing or equipment standard for one. Its only legal bases are 34 PNC Section 101, which uses the older Trust Territory-era terms ?clinics? and ?dispensaries,? and 34 PNC Section 332, which lists revenue from the ?Public Health/Community Center? as income of the Hospital Trust Fund. Secondary sources count CHCs differently; for example, one non-official source cites eight, including one on Kayangel. Treat the MHHS list of seven as authoritative. For desk research, search for ?Community Health Center,? ?CHC,? ?dispensary? and ?clinic? as possible names for the same primary-care facility, and record which term a source actually uses.</p>

        <h6 class="fw-bold"><b>Role</b></h6>
        <ul>
          <li>Serve as the first point of contact for primary, preventive and health-promotion care for individuals and families at every stage of life</li>
          <li>Deliver national public-health programs at community level, including immunization, family / maternal and child health, non-communicable disease screening and management, communicable disease control, and home health and geriatric care</li>
          <li>Refer patients to the Hospital when a case exceeds CHC capability</li>
        </ul>

        <h6 class="fw-bold"><b>Clinical Services</b></h6>
        <p><strong>Typical Bed Capacity</strong></p>
        <ul>
          <li>No inpatient beds reported. The CHCs work weekday daytime hours (6 AM?6 PM at the Koror and Airai centers), which indicates they are outpatient-only.</li>
        </ul>
        <p><strong>Diagnostic &amp; Support Infrastructure</strong></p>
        <ul>
          <li>Consultation, screening and immunization services</li>
          <li>Referral link to the Hospital for diagnostics, inpatient care and specialist review</li>
        </ul>
        <p class="text-justify"><em><strong>Note:</strong> Legal basis: 34 PNC Sections 101 and 332. The facility list, names and hours come from the MHHS website (healthypalau.pw, accessed October 2026). The Code does not document bed, staffing or equipment detail.</em></p>
